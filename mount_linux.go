//go:build linux

package sessionnet

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/sys/unix"
)

// setupMounts runs in the helper's private mount namespace. Nothing here is
// visible to, or modifies, the host: propagation is made private first, and
// every file the session sees is on an anonymous tmpfs in this namespace.
func setupMounts(req *initRequest) error {
	if err := unix.Mount("", "/", "", unix.MS_REC|unix.MS_PRIVATE, ""); err != nil {
		return fail(StageMount, "cannot make the session mount namespace private", err)
	}
	target, replaceParent, err := resolverTarget("/etc/resolv.conf")
	if err != nil {
		return fail(StageResolver, "cannot locate /etc/resolv.conf", err)
	}
	var nss string
	if req.IsolateDNS {
		original, err := os.ReadFile("/etc/nsswitch.conf")
		if err != nil {
			return fail(StageResolver, "cannot read /etc/nsswitch.conf for DNS isolation", err)
		}
		nss = isolatedNSS(string(original))
	}
	resolv := resolverConfig(req)

	// Write the private files on a scratch tmpfs that temporarily covers
	// /proc, then bind them into place. /proc always exists, it is about to
	// be replaced by the PID namespace's procfs anyway, and using it avoids
	// creating anything on a host filesystem.
	const scratch = "/proc"
	if err := unix.Mount("sessionnet", scratch, "tmpfs", unix.MS_NOSUID|unix.MS_NODEV|unix.MS_NOEXEC, "size=64k,mode=0755"); err != nil {
		return fail(StageResolver, "cannot create a private tmpfs for the session resolver", err)
	}
	mountErr := func() error {
		if err := os.WriteFile(filepath.Join(scratch, "resolv.conf"), []byte(resolv), 0o644); err != nil {
			return fail(StageResolver, "cannot write the session resolver", err)
		}
		if replaceParent {
			// The resolver symlink is dangling (for example systemd-resolved is
			// not running). Cover only its directory in this namespace.
			if err := bindPrivateDirectory(filepath.Join(scratch, "resolv.conf"), target); err != nil {
				return err
			}
		} else if err := bindReadOnly(filepath.Join(scratch, "resolv.conf"), target); err != nil {
			return fail(StageResolver, "cannot bind the session resolver over "+target, err)
		}
		if req.IsolateDNS {
			if err := os.WriteFile(filepath.Join(scratch, "nsswitch.conf"), []byte(nss), 0o644); err != nil {
				return fail(StageResolver, "cannot write the session nsswitch.conf", err)
			}
			nssTarget, err := filepath.EvalSymlinks("/etc/nsswitch.conf")
			if err != nil {
				return fail(StageResolver, "cannot resolve /etc/nsswitch.conf", err)
			}
			if err := bindReadOnly(filepath.Join(scratch, "nsswitch.conf"), nssTarget); err != nil {
				return fail(StageResolver, "cannot bind the session nsswitch.conf", err)
			}
		}
		return nil
	}()
	if err := unix.Unmount(scratch, unix.MNT_DETACH); err != nil {
		return errors.Join(mountErr, fail(StageMount, "cannot release the resolver scratch mount", err))
	}
	if mountErr != nil {
		return mountErr
	}
	// A procfs for this PID namespace. Without it, session processes would
	// see, and could ptrace through /proc paths, same-user host processes.
	if err := unix.Mount("proc", "/proc", "proc", unix.MS_NOSUID|unix.MS_NODEV|unix.MS_NOEXEC, ""); err != nil {
		return fail(StagePIDNamespace, "cannot mount /proc for the session PID namespace", err)
	}
	if req.IsolateDNS {
		// glibc can consult nscd before invoking any hosts NSS module. Mask
		// only its runtime directories in this private mount namespace.
		seen := make(map[string]bool)
		for _, path := range []string{"/run/nscd", "/var/run/nscd"} {
			resolved, err := filepath.EvalSymlinks(path)
			if errors.Is(err, os.ErrNotExist) {
				continue
			}
			if err != nil {
				return fail(StageResolver, "cannot resolve "+path, err)
			}
			if seen[resolved] {
				continue
			}
			seen[resolved] = true
			if err := unix.Mount("tmpfs", resolved, "tmpfs", unix.MS_NOSUID|unix.MS_NODEV|unix.MS_NOEXEC, "size=4k,mode=0755"); err != nil {
				return fail(StageResolver, "cannot mask the host nscd socket directory", err)
			}
		}
	}
	return nil
}

func resolverConfig(req *initRequest) string {
	var b strings.Builder
	b.WriteString("# Generated by sessionnet for this session only.\n")
	b.WriteString("nameserver " + req.GatewayIPv4 + "\n")
	if req.IPv6 && req.GatewayIPv6 != "" {
		b.WriteString("nameserver " + req.GatewayIPv6 + "\n")
	}
	b.WriteString("options timeout:2 attempts:2\n")
	return b.String()
}

func bindReadOnly(source, target string) error {
	if err := unix.Mount(source, target, "", unix.MS_BIND, ""); err != nil {
		var stat unix.Stat_t
		if errors.Is(err, unix.ENOENT) && unix.Stat(target, &stat) == nil && stat.Nlink == 0 {
			// The kernel cannot mount on an unlinked file, which is what an
			// older bind mount of a since-deleted temporary file looks like.
			return fmt.Errorf("%s is itself a bind mount of a deleted file: %w", target, err)
		}
		return err
	}
	return unix.Mount("", target, "", unix.MS_BIND|unix.MS_REMOUNT|unix.MS_RDONLY|unix.MS_NOSUID|unix.MS_NODEV|unix.MS_NOEXEC, "")
}

func bindPrivateDirectory(source, target string) error {
	dir := filepath.Dir(target)
	content, err := os.ReadFile(source)
	if err != nil {
		return fail(StageResolver, "cannot read the session resolver", err)
	}
	if err := unix.Mount("sessionnet", dir, "tmpfs", unix.MS_NOSUID|unix.MS_NODEV|unix.MS_NOEXEC, "size=16k,mode=0755"); err != nil {
		return fail(StageResolver, "cannot cover the resolver directory "+dir, err)
	}
	if err := os.WriteFile(target, content, 0o644); err != nil {
		return fail(StageResolver, "cannot write the session resolver", err)
	}
	if err := unix.Mount("", dir, "", unix.MS_REMOUNT|unix.MS_RDONLY|unix.MS_NOSUID|unix.MS_NODEV|unix.MS_NOEXEC, "size=16k,mode=0755"); err != nil {
		return fail(StageResolver, "cannot make the resolver directory read-only", err)
	}
	return nil
}

// resolverTarget follows symlinks the way the kernel does when mounting.
// It reports whether the final target is missing but its directory exists,
// in which case the directory itself must be covered.
func resolverTarget(path string) (string, bool, error) {
	resolved, err := filepath.EvalSymlinks(path)
	if err == nil {
		info, err := os.Stat(resolved)
		if err != nil {
			return "", false, err
		}
		if !info.Mode().IsRegular() {
			return "", false, fmt.Errorf("%s is not a regular file", resolved)
		}
		return resolved, false, nil
	}
	if !errors.Is(err, os.ErrNotExist) {
		return "", false, err
	}
	current := path
	for range 40 {
		link, err := os.Readlink(current)
		if errors.Is(err, os.ErrNotExist) {
			parent, err := filepath.EvalSymlinks(filepath.Dir(current))
			if err != nil {
				return "", false, fmt.Errorf("%s points to %s, whose directory does not exist", path, current)
			}
			if parent == "/" || parent == "/etc" {
				return "", false, fmt.Errorf("%s does not exist", current)
			}
			return filepath.Join(parent, filepath.Base(current)), true, nil
		}
		if err != nil {
			return "", false, err
		}
		if !filepath.IsAbs(link) {
			link = filepath.Join(filepath.Dir(current), link)
		}
		current = filepath.Clean(link)
	}
	return "", false, errors.New("too many levels of symbolic links")
}

// isolatedNSS replaces only the hosts database, preserving account lookups.
func isolatedNSS(original string) string {
	var result strings.Builder
	for _, line := range strings.Split(original, "\n") {
		key, _, found := strings.Cut(line, ":")
		if found && strings.TrimSpace(key) == "hosts" {
			continue
		}
		if line != "" {
			result.WriteString(line)
			result.WriteByte('\n')
		}
	}
	result.WriteString("hosts: files dns\n")
	return result.String()
}
